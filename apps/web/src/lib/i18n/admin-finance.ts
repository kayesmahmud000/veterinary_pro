export const getFinanceMessages = (locale: Locale) =>
  locale === "bn" ? bn : en;
export const financeLabel = (locale: Locale, value: string) =>
  labels[value]?.[locale === "bn" ? 1 : 0] ?? value;
export function financeError(locale: Locale, code?: string) {
  const t = getFinanceMessages(locale);
  return code?.includes("VERSION_CONFLICT") ||
    code?.includes("ACTION_UNAVAILABLE") ||
    ["TIMEOUT", "INVALID_RESPONSE"].includes(code ?? "")
    ? t.stale
    : code === "VALIDATION_FAILED"
      ? t.validation
      : code === "PASSWORD_CONFIRMATION_FAILED"
        ? t.passwordFailed
        : ["FORBIDDEN", "UNAUTHORIZED", "AUTHORIZATION_CHANGED"].includes(
              code ?? "",
            )
          ? t.denied
          : code === "NOT_FOUND"
            ? t.missing
            : code === "RATE_LIMITED"
              ? t.limited
              : t.unavailable;
}
